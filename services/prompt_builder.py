# services/prompt_builder.py

import json

from prompts.system_prompt import SYSTEM_PROMPT


def build_prompt(
    clinic_data: dict,
    history: str,
    user_message: str
) -> str:
    """
    Build the final prompt sent to Gemini.
    """

    return f"""
{SYSTEM_PROMPT}

========================================
سجل المحادثة
========================================

{history}

========================================
بيانات العيادة
========================================

{json.dumps(clinic_data, ensure_ascii=False, indent=2)}

========================================
رسالة العميل
========================================

{user_message}

========================================
التعليمات النهائية
========================================

- اقرأ سجل المحادثة أولاً.
- استخدم بيانات العيادة فقط.
- إذا كانت إجابة السؤال موجودة في سجل المحادثة فاستخدمها.
- إذا كانت موجودة في بيانات العيادة فاستخدمها.
- إذا لم تجد الإجابة فلا تخترع أي معلومة.
- إذا كانت المعلومة غير موجودة اعتذر بأدب.
- إذا كان العميل ذكر اسمه سابقًا ثم سأل عنه، استخدم سجل المحادثة للإجابة.
- إذا قال العميل "هو موجود إمتى؟" بعد ذكر اسم دكتور في الرسائل السابقة، افهم أنه يقصد نفس الدكتور.
- لا تخلط بين أيام حضور الطبيب وساعات عمل العيادة.
- اجعل الرد قصيرًا وواضحًا وباللهجة المصرية.
"""